/**
 * Turns tools-scraped squareDoctors.json into client/src/lib/realDoctors.js
 * matching the app's doctor schema. Unknown fields stay null — never invented.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const raw = JSON.parse(readFileSync(new URL('../client/src/lib/squareDoctors.json', import.meta.url), 'utf8'));

// lines that are really credentials, not specialties
const CRED_RX = /\(|\bBoard\b|^KSA$|^MRCPE$|^IFCAP$|Residency|^M\.?sc\b|^B\.?sc\b|^M\.?Phil\b|^FCCP|^MSSVD|^MCAP|^EDIC|^MRCR|^FIC\b|^Dip\b/i;

const ALIAS = {
  'Cardiologist': 'Cardiology', 'Interventional Cardiologist': 'Cardiology', 'Pediatric Cardiologist': 'Cardiology',
  'Cardiac Surgeon': 'Cardiac Surgery',
  'Surgeon': 'General Surgery', 'General Surgeon': 'General Surgery', 'Laparoscopic Surgeon': 'General Surgery',
  'Hepatobiliary Surgeon': 'General Surgery', 'Colorectal & Laparoscopic Surgeon': 'General Surgery', 'Plastic Surgeon': 'General Surgery',
  'Gynecologist & Obstetrician': 'Gynecology & Obstetrics', 'Gynecologic Oncologist': 'Gynecology & Obstetrics',
  'Pediatrician': 'Pediatrics', 'Neonatologist': 'Pediatrics', 'Pediatrician & Neonatologist': 'Pediatrics',
  'Pediatric Neurologist': 'Pediatrics', 'Pediatric Hematologist': 'Pediatrics', 'Pediatric Nephrologist': 'Pediatrics', 'Pediatric Pulmonologist': 'Pediatrics',
  'Orthopedist': 'Orthopedics',
  'Gastroenterologist': 'Gastroenterology',
  'Respiratory Specialist': 'Pulmonology', 'Pulmonologist': 'Pulmonology',
  'Oncologist': 'Oncology', 'Hematologist': 'Oncology',
  'Internal Medicine': 'Internal Medicine', 'Internal Medicine Specialist': 'Internal Medicine',
  'Maxillofacial and Dental Surgeon': 'Dentistry', 'Dentist': 'Dentistry',
  'Endocrinologist': 'Diabetes & Endocrinology', 'Diabetes Specialist': 'Diabetes & Endocrinology',
  'Nephrologist': 'Nephrology',
  'Neurologist': 'Neurology', 'Neurosurgeon': 'Neurosurgery',
  'Urologist': 'Urology',
  'Dermatologist': 'Dermatology',
  'Otolaryngologists (ENT)': 'ENT', 'Otolaryngologist': 'ENT',
  'Psychiatrist': 'Psychiatry',
  'Rheumatologist': 'Rheumatology',
  'Nutritionist': 'Nutrition & Dietetics',
  'Physical Medicine': 'Physical Medicine',
  'Radiologist': 'Radiology',
  'Pathologist': 'Pathology',
  'Anesthesiologist': 'Anesthesiology',
};

const seen = new Set();
const out = raw.map((d) => {
  const creds = d.specialties.filter((s) => CRED_RX.test(s));
  const realSpecs = d.specialties.filter((s) => !CRED_RX.test(s));
  const specialty = ALIAS[realSpecs[0]] ?? realSpecs[0] ?? 'Specialist';

  let slug = d.slug;
  while (seen.has(slug)) slug = `${slug}-2`;
  seen.add(slug);

  return {
    slug,
    name: d.name,
    nameBn: null,
    gender: null,
    specialty,
    degrees: [...d.degrees, ...creds],
    designation: realSpecs.join(' · ') || null,
    workplace: null,
    experienceYears: d.experienceYears ?? null,
    languages: null,
    bmdcRegNo: d.bmdcRegNo ?? null,
    rating: null,
    reviewsCount: 0,
    reviews: [],
    featured: false,
    phone: d.phone ?? null,
    email: null,
    about: null,
    services: d.services ?? [],
    source: d.source,
    sourceUrl: d.sourceUrl,
    chambers: d.chambers.map((c) => ({
      name: c.name.replace(/^Square Hospitals Ltd$/, 'Square Hospitals Ltd.'),
      address: c.address,
      district: c.district,
      room: null,
      phone: null,
      fee: null,
      followUpFee: null,
      schedule: c.schedule,
    })),
  };
});

const body = `// Real doctor listings imported from sasthyaseba.com (facts only; unknown fields are null).
// Generated by tools/transform-real.mjs — do not edit by hand.
export const REAL_DOCTORS = ${JSON.stringify(out, null, 1)};
`;
writeFileSync(new URL('../client/src/lib/realDoctors.js', import.meta.url), body);
console.log('written:', out.length, 'doctors');
console.log('final specialties:', JSON.stringify([...new Set(out.map((x) => x.specialty))]));